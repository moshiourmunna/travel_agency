// Generates backend/resources/js/admin/components/icons.gen.ts: only the lucide icons the admin can actually show.
// Any quoted kebab-case string in the admin PHP/TSX sources that is a lucide icon name (or an ALIAS key) is included,
// so server-sent names (nav, resources, actions, settings groups) keep working. Run after adding icons: node tooling/gen_admin_icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const be = path.join(root, 'backend');
const require = createRequire(path.join(be, 'package.json'));
const { icons } = require('lucide-react');
const pascal = (s) => s.replace(/(^|[-_ ])([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const iconSrc = fs.readFileSync(path.join(be, 'resources/js/admin/components/Icon.tsx'), 'utf8');
const alias = Object.fromEntries([...iconSrc.matchAll(/'?([a-z0-9-]+)'?:\s*'([a-z0-9-]+)'/g)].map((m) => [m[1], m[2]]));
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(php|tsx?|json)$/.test(f.name)) files.push(p); } };
['app', 'config', 'database/seeders', 'resources/js/admin', 'lang'].forEach((d) => fs.existsSync(path.join(be, d)) && walk(path.join(be, d)));
const found = new Set(['circle']);
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) {
  const n = alias[m[1]] ?? m[1];
  if (icons[pascal(n)]) found.add(n);
}
const names = [...found].sort();
const out = `// GENERATED by tooling/gen_admin_icons.mjs — do not edit by hand.\nimport { ${names.map(pascal).join(', ')} } from 'lucide-react';\n\nexport const ICONS: Record<string, typeof Circle> = { ${names.map((n) => `'${n}': ${pascal(n)}`).join(', ')} };\n`;
fs.writeFileSync(path.join(be, 'resources/js/admin/components/icons.gen.ts'), out);
console.log(`${names.length} icons`);
