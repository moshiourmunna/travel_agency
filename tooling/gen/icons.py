"""Generate frontend/components/icons/data.ts: lucide (+custom brand) icon bodies used by the mockup templates, seed data and the Next app."""
import os, re, json, glob
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
LUCIDE = os.path.join(ROOT, 'tooling', 'node_modules', 'lucide-static', 'icons')
CUSTOM = os.path.join(ROOT, 'src', 'icons')
names = set()
for f in glob.glob(os.path.join(ROOT, 'src', '**', '*.*'), recursive=True):
    if f.endswith(('.html', '.py', '.js')):
        s = open(f, encoding='utf-8').read()
        names |= set(re.findall(r"icon\(\s*'([a-z0-9-]+)'", s))
        names |= set(re.findall(r"\('([a-z0-9-]+)',\s*\(", s))  # (icon,(en,bn)) tuples
        names |= set(re.findall(r"'icon':\s*'([a-z0-9-]+)'", s))
for f in glob.glob(os.path.join(ROOT, 'backend', 'database', 'seeders', 'data', '*.json')):
    s = open(f, encoding='utf-8').read()
    names |= set(re.findall(r'"([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"', s))
for f in glob.glob(os.path.join(ROOT, 'frontend', '{app,components,lib}', '**', '*.tsx'), recursive=True) + glob.glob(os.path.join(ROOT, 'frontend', 'app', '**', '*.tsx'), recursive=True) + glob.glob(os.path.join(ROOT, 'frontend', 'components', '**', '*.tsx'), recursive=True):
    s = open(f, encoding='utf-8').read()
    names |= set(re.findall(r'(?:name|icon)="([a-z0-9-]+)"', s))
names |= set(json.load(open(os.path.join(ROOT, 'tooling', 'gen', 'extra_icons.json')))) if os.path.exists(os.path.join(ROOT, 'tooling', 'gen', 'extra_icons.json')) else set()
names.add('book-user')
out = {}
for n in sorted(names):
    p = os.path.join(CUSTOM, n + '.svg')
    if not os.path.exists(p):
        p = os.path.join(LUCIDE, n + '.svg')
    if not os.path.exists(p):
        continue
    raw = re.sub(r'<!--.*?-->', '', open(p).read(), flags=re.S)
    m = re.search(r'<svg([^>]*)>(.*)</svg>', raw, re.S)
    attrs, body = m.group(1), re.sub(r'\s*\n\s*', '', m.group(2)).strip()
    filled = 'fill="currentColor"' in attrs and 'stroke=' not in attrs
    out[n] = [body, 1 if filled else 0]
src = '// GENERATED by tooling/gen/icons.py — do not edit. [svg inner markup, filled?]\n'
src += 'export const ICONS: Record<string, [string, number]> = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n'
open(os.path.join(ROOT, 'frontend', 'components', 'icons', 'data.ts'), 'w').write(src)
print(len(out), 'icons')
