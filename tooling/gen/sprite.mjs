// Builds frontend/public/icons.svg (one <symbol> per icon in components/icons/data.ts) and components/icons/sprite.ts
// (versioned URL). Pages then reference icons with <use href> instead of repeating inline paths in every HTML/RSC payload.
// Run after regenerating data.ts: node tooling/gen/sprite.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const fe = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../frontend');
const src = fs.readFileSync(path.join(fe, 'components/icons/data.ts'), 'utf8');
const ICONS = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
const symbols = Object.entries(ICONS).map(([n, [body]]) => `<symbol id="${n}" viewBox="0 0 24 24">${body.replace(/\s*\/>/g, '/>')}</symbol>`).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg">${symbols}</svg>`;
fs.writeFileSync(path.join(fe, 'public/icons.svg'), svg);
const v = crypto.createHash('sha1').update(svg).digest('hex').slice(0, 10);
fs.writeFileSync(path.join(fe, 'components/icons/sprite.ts'), `// GENERATED by tooling/gen/sprite.mjs\nexport const SPRITE = '/icons.svg?v=${v}';\n/** name → 1 when the icon is filled (fill) instead of stroked */\nexport const ICON_NAMES: Record<string, 0 | 1> = ${JSON.stringify(Object.fromEntries(Object.entries(ICONS).map(([n, [, f]]) => [n, f ? 1 : 0])))};\n`);
console.log(Object.keys(ICONS).length, 'icons,', svg.length, 'bytes, v', v);
